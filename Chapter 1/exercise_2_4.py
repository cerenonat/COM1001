# 2.4 (Arithmetic)
# For each of the arithmetic operators +, -, *, /, // and **, display the value with 27.5 and 2.

print('27.5 + 2 =', 27.5 + 2)
print('27.5 - 2 =', 27.5 - 2)
print('27.5 * 2 =', 27.5 * 2)
print('27.5 / 2 =', 27.5 / 2)
print('27.5 // 2 =', 27.5 // 2)
print('27.5 ** 2 =', 27.5 ** 2)
